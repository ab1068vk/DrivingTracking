import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const disclosurePath = path.join(repoRoot, 'src', 'lib', 'legalDisclaimers.js');
const generatedPath = path.join(repoRoot, 'src', 'lib', 'legalNoticeVersion.generated.js');
const checkOnly = process.argv.includes('--check');

/** Hash scheme identifier. Bump only if the serialization itself changes. */
const HASH_SCHEME = 'sha256-legal-notice-v1';

/**
 * Normalizes representation, never meaning.
 *
 * Line-ending and surrounding-whitespace differences are how the same sentence gets written on
 * two machines; they are not a change to what the user is told. Anything else - a reworded
 * sentence, a new data category, a changed retention period - must change the hash.
 */
const normalizeText = (value) => String(value)
  .replace(/\r\n/g, '\n')
  .trim();

const stableSerialize = (value) => {
  if (value === null) return 'null';
  const valueType = typeof value;
  if (valueType === 'string') return JSON.stringify(normalizeText(value));
  if (valueType === 'number') return Number.isFinite(value) ? String(value) : JSON.stringify(String(value));
  if (valueType === 'boolean') return JSON.stringify(value);
  if (valueType === 'undefined') return '"__undefined__"';
  if (Array.isArray(value)) return `[${value.map(stableSerialize).join(',')}]`;
  if (valueType === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableSerialize(value[key])}`)
      .join(',')}}`;
  }
  return JSON.stringify(`[unsupported:${valueType}]`);
};

const generatedSource = (version, hash) => `/**
 * Generated by scripts/generate-legal-version.mjs.
 * Do not edit by hand.
 *
 * LEGAL_NOTICE_CONTENT_HASH identifies the substantive disclosure content that
 * LEGAL_NOTICE_ACK_VERSION ${version} presents. An acknowledgement stored with this hash can be
 * proven to refer to this exact content.
 */
export const LEGAL_NOTICE_CONTENT_HASH = '${hash}';
export const LEGAL_NOTICE_HASHED_VERSION = ${version};
`;

// Compare content, not bytes: git checks this file out with CRLF wherever core.autocrlf is
// enabled, while the generator always emits LF.
const normalizeEol = (source) => source.replace(/\r\n/g, '\n');

const disclosureUrl = `${pathToFileURL(disclosurePath).href}?legal-version=${Date.now()}`;
const disclosureModule = await import(disclosureUrl);
const canonical = disclosureModule.canonicalLegalNoticeContent();

const hashInput = `${HASH_SCHEME}\n${stableSerialize(canonical)}`;
const hash = `${HASH_SCHEME}:${createHash('sha256').update(hashInput).digest('hex').slice(0, 32)}`;
const version = Number(canonical.version);

const nextSource = generatedSource(version, hash);
const currentSource = readFileSync(generatedPath, 'utf8');
const isUpToDate = normalizeEol(currentSource) === normalizeEol(nextSource);

const previousHash = (currentSource.match(/LEGAL_NOTICE_CONTENT_HASH = '([^']*)'/) || [, ''])[1];
const previousVersion = Number((currentSource.match(/LEGAL_NOTICE_HASHED_VERSION = (\d+)/) || [, '0'])[1]);

/**
 * Strict content binding: an acknowledgement records the exact disclosure content presented.
 *
 * So regenerating a different hash under the SAME acknowledgement version is never safe. Every
 * user who acknowledged the previous content would silently become `content_mismatch` and be
 * pushed back through the dialog with no changelog explaining why. Refuse it.
 *
 * Representation-only edits (styling, layout, line endings, surrounding whitespace) do not reach
 * here at all, because they do not change the canonical hash.
 */
const wouldDriftSameVersion = previousHash !== ''
  && previousVersion === version
  && previousHash !== hash;

const driftGuidance = () => {
  console.error('');
  console.error('The canonical disclosure content changed, so it is no longer the content that');
  console.error(`acknowledgement version ${version} recorded. Existing acknowledgements are bound`);
  console.error('to the previous content and would silently require re-review.');
  console.error('');
  console.error('Raise LEGAL_NOTICE_ACK_VERSION in src/lib/legalDisclaimers.js, add a');
  console.error('LEGAL_NOTICE_CHANGELOG entry describing the change, then run:');
  console.error('  npm run legal:version');
  console.error('');
  console.error('This applies to ANY canonical text change, including a spelling correction:');
  console.error('the acknowledgement binds the exact text presented. Styling, layout and');
  console.error('line-ending changes do not reach this guard because they are excluded from');
  console.error('the canonical content.');
};

if (checkOnly) {
  if (!isUpToDate) {
    console.error('Legal notice content hash is stale.');
    console.error(`Expected ${hash} for acknowledgement version ${version}.`);
    if (wouldDriftSameVersion) driftGuidance();
    else {
      console.error('');
      console.error('Run: npm run legal:version');
    }
    process.exit(1);
  }
  console.log(`Legal notice version ${version} content hash is current.`);
} else if (wouldDriftSameVersion) {
  // Refuse rather than write. Regenerating here is the one action that silently invalidates
  // real users' acknowledgements, so it must not be a side effect of running the generator.
  console.error(`Refusing to rebind acknowledgement version ${version} to different content.`);
  console.error(`  recorded: ${previousHash}`);
  console.error(`  current:  ${hash}`);
  driftGuidance();
  process.exit(1);
} else if (!isUpToDate) {
  writeFileSync(generatedPath, nextSource);
  console.log(`Generated legal notice content hash for version ${version}.`);
} else {
  console.log(`Legal notice version ${version} content hash is current.`);
}
